import { describe, it, expect } from 'vitest'
import { applyDictation } from '../applyDictation'

/**
 * ТП-212: правило вставки надиктованного текста. Главное здесь — не потерять
 * ни надиктованное, ни правки пользователя.
 */
describe('applyDictation (ТП-212)', () => {
  describe('первая вставка (replaces не задан)', () => {
    it('в пустое поле кладёт текст как есть', () => {
      expect(applyDictation('', 'Новый текст')).toBe('Новый текст')
    })

    it('к непустому полю дописывает через разделитель', () => {
      expect(applyDictation('Было.', 'Стало.')).toBe('Было.\nСтало.')
    })

    it('разделитель настраивается (комментарий дописывает через пробел)', () => {
      expect(applyDictation('Было.', 'Стало.', { separator: ' ' })).toBe('Было. Стало.')
    })
  })

  describe('подмена улучшенным вариантом', () => {
    it('заменяет ранее вставленный фрагмент, сохраняя остальной текст', () => {
      const current = 'Вступление.\nсырой надиктованный текст'
      const next = applyDictation(current, 'Сырой надиктованный текст.', {
        replaces: 'сырой надиктованный текст',
      })
      expect(next).toBe('Вступление.\nСырой надиктованный текст.')
    })

    it('заменяет ПОСЛЕДНЮЮ вставку, если одинаковый текст диктовали дважды', () => {
      const current = 'привет\nпривет'
      expect(applyDictation(current, 'Привет!', { replaces: 'привет' })).toBe(
        'привет\nПривет!',
      )
    })

    it('пользователь успел изменить текст — улучшение отбрасывается, поле не трогаем', () => {
      const edited = 'совсем другой текст, написанный руками'
      expect(applyDictation(edited, 'Улучшенный вариант.', { replaces: 'исходный' })).toBe(
        edited,
      )
    })

    it('пустое поле после очистки пользователем — ничего не восстанавливаем', () => {
      expect(applyDictation('', 'Улучшенный вариант.', { replaces: 'исходный' })).toBe('')
    })
  })
})
