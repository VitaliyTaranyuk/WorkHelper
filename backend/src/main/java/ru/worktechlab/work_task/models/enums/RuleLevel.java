package ru.worktechlab.work_task.models.enums;

import lombok.Getter;

/**
 * Уровень переносимости правила (ADR-018, разбор {@code .ai/RULES_TAXONOMY.md}).
 *
 * <p>Уровень — поле правила, а не отдельная сущность: ради трёх значений заводить
 * иерархию наборов означало бы усложнение без пользы. Промоушен правила между
 * уровнями — смена поля, а не перенос между таблицами.
 *
 * <p>Порядок констант несёт смысл: ядро идёт первым, профиль последним — именно
 * в этом порядке правила показываются и выгружаются. Полагаться на алфавит
 * нельзя, поэтому сортировка идёт по {@link #ordinal()} в коде, а не через
 * {@code ORDER BY} по строковой колонке.
 */
@Getter
public enum RuleLevel {
    CORE("Ядро — переносится в любой проект"),
    PACK("Пак — переносится в проекты того же класса"),
    PROFILE("Профиль — принадлежит конкретному проекту");

    private final String description;

    RuleLevel(String description) {
        this.description = description;
    }
}
